def benchmark(interpreter, sample, runs=100, warmup=10):
    # Warm-up runs
    for _ in range(warmup):
        predict(interpreter, sample)

    # Measure 100 individual inferences
    times_ms = []
    for _ in range(runs):
        start = time.perf_counter()
        predict(interpreter, sample)
        end = time.perf_counter()
        times_ms.append((end - start) * 1000)

    return np.mean(times_ms), np.median(times_ms)

# Approximate Python process memory before benchmarking
process = psutil.Process(os.getpid())
memory_before_mb = process.memory_info().rss / (1024 ** 2)

