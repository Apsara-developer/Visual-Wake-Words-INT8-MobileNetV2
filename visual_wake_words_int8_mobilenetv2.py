def prepare_input(image, details):
    dtype = details["dtype"]
    image = image.astype(np.float32)

    if np.issubdtype(dtype, np.integer):
        scale, zero_point = details["quantization"]
        if scale == 0:
            raise ValueError("Invalid input quantization scale")
        image = np.round(image / scale + zero_point)
        limits = np.iinfo(dtype)
        image = np.clip(image, limits.min, limits.max)

    return image.astype(dtype)

def predict(interpreter, image):
    details = interpreter.get_input_details()[0]
    output_details = interpreter.get_output_details()[0]

    input_data = prepare_input(image, details)
    interpreter.set_tensor(details["index"], input_data)
    interpreter.invoke()

    return interpreter.get_tensor(output_details["index"])

# Get one sample from the validation dataset
