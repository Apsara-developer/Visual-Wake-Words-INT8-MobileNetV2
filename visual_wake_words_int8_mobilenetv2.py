def evaluate_tflite(interpreter, dataset):
    input_info = interpreter.get_input_details()[0]
    output_info = interpreter.get_output_details()[0]

    correct = 0
    total = 0

    for images, labels in dataset:
        images = images.numpy()
        labels = labels.numpy()

        for i in range(len(images)):
            image = images[i:i+1].astype(np.float32)

            dtype = input_info["dtype"]
            if np.issubdtype(dtype, np.integer):
                scale, zero = input_info["quantization"]
                image = np.round(image / scale + zero)
                limits = np.iinfo(dtype)
                image = np.clip(image, limits.min, limits.max)

            interpreter.set_tensor(
                input_info["index"], image.astype(dtype)
            )
            interpreter.invoke()

            output = interpreter.get_tensor(output_info["index"])
            if np.issubdtype(output_info["dtype"], np.integer):
                scale, zero = output_info["quantization"]
                output = (output.astype(np.float32) - zero) * scale

            if np.argmax(output[0]) == int(labels[i]):
                correct += 1
            total += 1

    return 100 * correct / total, total

